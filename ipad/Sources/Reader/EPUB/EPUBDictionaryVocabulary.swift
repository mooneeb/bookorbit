  static func normalizeLanguage(_ value: String) -> String {
    let primary =
      EPUBLanguageToolTransport.trim(value).lowercased()
      .components(separatedBy: CharacterSet(charactersIn: ";,/|")).first ?? ""
    let base =
      primary.components(separatedBy: "-").first?
      .trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
    if let alias = aliases[base] { return alias }
    if base.range(of: "^[a-z]{2,3}$", options: .regularExpression) != nil { return base }
    return "en"
  }

  static func pointerLemma(_ value: String) -> String? {
    let value = EPUBLanguageToolTransport.trim(value)
    let pattern =
      #"^(?:\([^)]*\)\s*)?([\p{L}\p{M}/ -]+?)\s+of\s+([\p{L}\p{M}][\p{L}\p{M}'’-]*)\s*[.:;,]?$"#
    guard let regex = try? NSRegularExpression(pattern: pattern),
      let match = regex.firstMatch(in: value, range: NSRange(value.startIndex..., in: value)),
      let modifiersRange = Range(match.range(at: 1), in: value),
      let lemmaRange = Range(match.range(at: 2), in: value)
    else { return nil }
    let modifiers = value[modifiersRange].lowercased().components(
      separatedBy: CharacterSet.whitespacesAndNewlines.union(CharacterSet(charactersIn: "/"))
    )
    .filter { !$0.isEmpty }
    guard !modifiers.isEmpty, modifiers.allSatisfy(grammarTerms.contains),
      !modifiers.allSatisfy({ ["a", "an", "the", "and", "or"].contains($0) })
    else { return nil }
    return value[lemmaRange].lowercased()
  }

  static func plainText(_ html: String) -> String {
    // Provider markup is never loaded into WebKit or an HTML attributed-string renderer.
    var value = html.replacingOccurrences(
      of: #"(?is)<(script|style)\b[^>]*>.*?(?:</\1\s*>|$)"#, with: "", options: .regularExpression)
    value = value.replacingOccurrences(
      of: #"(?s)<!--.*?(?:-->|$)|<[^>]*>"#, with: "", options: .regularExpression)
    if let regex = try? NSRegularExpression(
      pattern: #"&(#x[0-9a-fA-F]+|#[0-9]+|[a-zA-Z][a-zA-Z0-9]+);"#)
    {
      let matches = regex.matches(in: value, range: NSRange(value.startIndex..., in: value))
      for match in matches.reversed() {
        guard let range = Range(match.range, in: value),
          let nameRange = Range(match.range(at: 1), in: value)
        else { continue }
        let name = String(value[nameRange])
        let code: UInt32?
        if name.hasPrefix("#x") {
          code = UInt32(name.dropFirst(2), radix: 16)
        } else if name.hasPrefix("#") {
          code = UInt32(name.dropFirst())
        } else {
          code = entities[name]
        }
        if let code, let scalar = UnicodeScalar(code), code != 0 {
          value.replaceSubrange(range, with: String(scalar))
        }
      }
    }
    return value.replacingOccurrences(of: #"\s+"#, with: " ", options: .regularExpression)
      .trimmingCharacters(in: .whitespacesAndNewlines)
  }

